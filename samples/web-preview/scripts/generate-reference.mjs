#!/usr/bin/env node
/* global process, console */
/**
 * Generates src/model/reference-data.ts, the descriptions, operators, return types and examples of the functions
 * and procedures shown by the API reference page, from the function and procedure indexes of the FormuLang standard.
 * Run it after a new version of the standard:
 *
 *   node scripts/generate-reference.mjs [path of a checkout of the standard, default: ../../../FormuLang]
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const standard = resolve(process.argv[2] ?? join(root, "..", "..", "..", "FormuLang"));
const docs = join(standard, "docs", "standards");

const INDEXES = [
  ["core", join(docs, "core", "functions", "README.md")],
  ["core", join(docs, "core", "procedures", "README.md")],
  ["stock", join(docs, "stock", "functions", "README.md")],
];

/** Return types of the functions whose table has none (control flow, procedures, OBJECT). */
const RETURN_TYPES = {
  IF: "Any",
  ERROR: "Error",
  IFNULL: "Any",
  IFERR: "Any",
  RECALL: "Any",
  CALL: "Any",
  OBJECT: "Object",
};
const PROCEDURE_RETURN = "Error (SUCCESS)";

/** Cells of a table row; `\|` is a `|` inside a cell. */
const cells = (row) =>
  row
    .trim()
    .replace(/^\||\|$/g, "")
    .split(/(?<!\\)\|/)
    .map((cell) => cell.trim().replaceAll("\\|", "|"));

/** Markdown of a cell as plain text with `code` kept: links become their text, "[[Read more]]" is removed. */
const plain = (text) =>
  text
    .replace(/\[\[Read more\]\]\([^)]*\)/g, "")
    .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1")
    .replace(/\s+/g, " ")
    .trim();

const types = (text) =>
  plain(text)
    .split("/")
    .map((type) => type.replaceAll("`", "").trim())
    .filter((type) => type.length > 0);

const entries = new Map();
for (const [standardId, path] of INDEXES) {
  const procedures = path.includes("procedures");
  let header;
  for (const line of readFileSync(path, "utf8").split(/\r?\n/)) {
    if (!line.startsWith("|")) {
      header = undefined;
      continue;
    }
    const row = cells(line);
    if (header === undefined) {
      header = row.map((cell) => cell.toLowerCase());
      continue;
    }
    if (row.every((cell) => /^:?-+:?$/.test(cell))) continue;
    const name = /`([A-Z_][A-Z0-9_]*)\(/.exec(row[0])?.[1];
    if (name === undefined) continue;
    const column = (title) => {
      const index = header.indexOf(title);
      return index < 0 ? undefined : row[index];
    };
    const description = plain(column("description") ?? "");
    const operator = plain(column("operator") ?? "").replaceAll("`", "");
    const returns = column("return type");
    const example = column("example");
    const entry = entries.get(name) ?? {
      standard: standardId,
      descriptions: [],
      returns: [],
      operator: undefined,
      example: undefined,
    };
    if (description.length > 0 && !entry.descriptions.includes(description)) entry.descriptions.push(description);
    for (const type of returns === undefined ? [] : types(returns)) {
      if (!entry.returns.includes(type)) entry.returns.push(type);
    }
    if (operator.length > 0) entry.operator = operator;
    if (example !== undefined && example.length > 0) entry.example = plain(example).replaceAll("`", "");
    if (procedures && entry.returns.length === 0) entry.returns.push(PROCEDURE_RETURN);
    entries.set(name, entry);
  }
}
for (const [name, type] of Object.entries(RETURN_TYPES)) {
  const entry = entries.get(name);
  if (entry !== undefined && entry.returns.length === 0) entry.returns.push(type);
}
entries.set("OBJECT", {
  standard: "core",
  descriptions: ["Creates an Object from key-value pairs; the object literal `{ k: v }` is translated into it."],
  returns: ["Object"],
  operator: "{ }",
  example: 'OBJECT("a", 1)',
});

const git = (...args) => execFileSync("git", ["-C", standard, ...args], { encoding: "utf8" }).trim();
let revision = git("rev-parse", "--short", "HEAD");
if (git("status", "--porcelain", "--", "docs").length > 0) revision += " (with uncommitted changes)";

const sorted = [...entries].sort(([a], [b]) => a.localeCompare(b));
const body = sorted.map(([name, e]) => `  ${name}: ${JSON.stringify(e)},`).join("\n");
const output = `// Generated by scripts/generate-reference.mjs from Adisoreq/FormuLang@${revision} (the function and procedure
// indexes of the standards). Do not edit it by hand: run the script again.

/** Description of a function or procedure in the indexes of the standard. */
export interface ReferenceDescription {
  /** \`core\` or \`stock\`. */
  readonly standard: string;
  /** Descriptions (Markdown with \`code\`), one for every table that lists the function. */
  readonly descriptions: readonly string[];
  /** Return types, e.g. \`["Number", "Null"]\`. */
  readonly returns: readonly string[];
  /** Operator form, e.g. \`+\`. */
  readonly operator?: string | undefined;
  readonly example?: string | undefined;
}

export const REFERENCE: Readonly<Record<string, ReferenceDescription>> = {
${body}
};
`;
writeFileSync(join(root, "src", "model", "reference-data.ts"), output);
console.log(`Wrote ${sorted.length} descriptions from Adisoreq/FormuLang@${revision}.`);
